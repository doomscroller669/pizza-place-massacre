"""Pack tools/faces/<who>-<expr>.jpg into src/js/06-facedata.js: 128x128 JPEGs as data URLs, plus each face's
eye and mouth positions (in 128-pixel units) for the in-game blink and jaw."""
import json, base64, io, pathlib
from PIL import Image
root = pathlib.Path(__file__).resolve().parent.parent
src = root / 'tools' / 'faces'
marks = json.loads((src / 'landmarks.json').read_text())
data, mk = {}, {}
for who, m in marks.items():
    for f in sorted(src.glob(f'{who}-*.jpg')):
        expr = f.stem.split('-', 1)[1]
        n = 256 if who == 'toni' else 128   # Toni's mask gets twice the pixels: it's the face the player sees closest
        b = io.BytesIO(); Image.open(f).convert('RGB').resize((n, n), Image.LANCZOS).save(b, 'JPEG', quality=86)
        data.setdefault(who, {})[expr] = 'data:image/jpeg;base64,' + base64.b64encode(b.getvalue()).decode()
    mk[who] = {k: ([round(v[0] / 2, 1), round(v[1] / 2, 1)] if k != 'back' else v) for k, v in m.items()}
    # skin tone for the neck and hands: the cheeks under each eye, a little darker since the photo was lit for a studio
    import numpy as np
    a = np.array(Image.open(src / f'{who}-neutral.jpg').convert('RGB')).astype(float)
    ch = (a[106:132, 120:136].reshape(-1, 3) if who == 'toni' else   # Toni: the bare stocking between his eyes
          np.concatenate([a[int(m[e][1]) + 22:int(m[e][1]) + 36, int(m[e][0]) - 6:int(m[e][0]) + 6].reshape(-1, 3) for e in ('eyeR', 'eyeL')]))
    mk[who]['skin'] = '#%02x%02x%02x' % tuple(int(v * 0.86) for v in np.median(ch, axis=0))
js = ('/* GENERATED by tools/faces_pack.py: photo faces (fictional, generated by tools/faces.py) and their landmarks. Do not edit. */\n'
      'const FACE_DATA=' + json.dumps(data, separators=(',', ':')) + ';\nconst FACE_MARKS=' + json.dumps(mk, separators=(',', ':')) + ';\n')
(root / 'src/js/06-facedata.js').write_text(js)
print(len(data), 'faces,', round(len(js) / 1024), 'KB')
